const originalText = new WeakMap();
const originalAlt = new WeakMap();
const languageTags = {
  ar: ["ar", "rtl"],
  en: ["en", "ltr"],
  es: ["es", "ltr"],
  fr: ["fr", "ltr"],
  de: ["de", "ltr"],
  pt: ["pt", "ltr"],
  ru: ["ru", "ltr"],
  zh: ["zh-CN", "ltr"],
  ja: ["ja", "ltr"],
  hi: ["hi", "ltr"],
};

const translatePage = (language) => {
  const dictionary = messages[language] || {};
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;

  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) {
      originalText.set(node, node.nodeValue);
    }

    const source = originalText.get(node);
    const trimmed = source.trim();
    const translated = dictionary[trimmed];

    if (translated) {
      const leading = source.match(/^\s*/)?.[0] || "";
      const trailing = source.match(/\s*$/)?.[0] || "";
      const replacement = `${leading}${translated}${trailing}`;
      if (node.nodeValue !== replacement) {
        node.nodeValue = replacement;
      }
    } else {
      if (node.nodeValue !== source) {
        node.nodeValue = source;
      }
    }
  }

  document.querySelectorAll("img[alt]").forEach((image) => {
    if (!originalAlt.has(image)) {
      originalAlt.set(image, image.alt);
    }
    image.alt = dictionary[originalAlt.get(image)] || originalAlt.get(image);
  });

  const [locale, direction] = languageTags[language] || languageTags.en;
  document.documentElement.lang = locale;
  document.documentElement.dir = direction;
  document.title = dictionary[sourceTitle] || sourceTitle;
  languageSelect.value = language;
  languageSelect.setAttribute(
    "aria-label",
    dictionary.Language || languageNames[language],
  );
};

let savedLanguage = "ar";
try {
  const storedLanguage = localStorage.getItem(currentLanguageKey);
  if (storedLanguage && languageNames[storedLanguage]) {
    savedLanguage = storedLanguage;
  }
} catch (error) {
  console.warn("Could not read the saved language preference:", error);
}

languageSelect.addEventListener("change", () => {
  const language = languageSelect.value;
  translatePage(language);
  try {
    localStorage.setItem(currentLanguageKey, language);
  } catch (error) {
    console.warn("Could not save the language preference:", error);
  }
});

translatePage(savedLanguage);

const localizedWeatherStatus = document.querySelector("#weather-status");
if (localizedWeatherStatus) {
  const statusObserver = new MutationObserver(() => {
    translatePage(languageSelect.value);
  });
  statusObserver.observe(localizedWeatherStatus, {
    childList: true,
    characterData: true,
    subtree: true,
  });
}
